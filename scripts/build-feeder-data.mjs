/* Build the one-page-toys practice feeder's data.js from PRACTICE puzzles only.
 *
 *   node scripts/build-feeder-data.mjs [path/to/one-page-toys]
 *
 * ⚠ The feeder used to ship "DAILY + PRACTICE, deduped": 91 of its 132 puzzles
 * were real spellingblocks.com dailies, and its hint tried the stored solution
 * words first, so on most rounds the hint handed over a daily's answer. The
 * feeder is a practice edition by house rule; it gets practice puzzles and
 * nothing else. Re-run after `node scripts/gen-practice.mjs`, then bump the
 * feeder's ?v= on data.js.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const opt = process.argv[2] || path.resolve("..", "one-page-toys");
const out = path.join(opt, "toys", "spelling-blocks", "data.js");

const src = fs.readFileSync("src/data/practice-solutions.ts", "utf8");
const solutions = [...src.slice(src.indexOf("= [")).matchAll(/\[([^\[\]]+)\]/g)]
  .map(m => [...m[1].matchAll(/"([A-Z]+)"/g)].map(x => x[1]))
  .filter(x => x.length);

const dict = require("an-array-of-english-words")
  .filter(w => w.length >= 3 && w.length <= 9 && /^[a-z]+$/.test(w))
  .map(w => w.toUpperCase());

// same seeded shuffle idea as the site, so block order is stable between builds
function shuffled(arr, seed) {
  let s = seed >>> 0;
  const rng = () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

const puzzles = solutions.map((s, i) => {
  const letters = s.join("").split("");
  if (letters.length !== 12) throw new Error(`not 12 letters: ${s.join("+")}`);
  return { b: shuffled(letters, 5000 + i).join(""), p: s.length, s };
});

// every dictionary word buildable from at least one puzzle's 12 letters
const counts = puzzles.map(p => { const m = {}; for (const c of p.b) m[c] = (m[c] || 0) + 1; return m; });
const fits = (w, m) => { const need = {}; for (const c of w) { need[c] = (need[c] || 0) + 1; if (need[c] > (m[c] || 0)) return false; } return true; };
const words = dict.filter(w => counts.some(m => fits(w, m)));

const header = `/* Spelling Blocks - feeder puzzle data (generated by scripts/build-feeder-data.mjs in the
 * spelling-blocks repo; do not hand-edit).
 * words: every dictionary word (3-9 letters) buildable from any practice puzzle's 12 letters, so word
 *   validation is a single Set lookup. Source dict: an-array-of-english-words.
 * puzzles: PRACTICE puzzles only. The daily puzzles never ship here: practice must never preview a
 *   daily. Grouped by par: Easy = 2 words, Medium = 3, Hard = 4. b = 12 shuffled block letters,
 *   p = par, s = intended solution words (used only for the optional hint). */
`;
fs.writeFileSync(out, header + "window.SB_DATA=" + JSON.stringify({ words, puzzles }) + ";\n");
const byPar = [2, 3, 4].map(p => puzzles.filter(x => x.p === p).length);
console.log(`wrote ${out}: ${puzzles.length} practice puzzles (easy ${byPar[0]}, medium ${byPar[1]}, hard ${byPar[2]}), ${words.length} words, ${(fs.statSync(out).size / 1024).toFixed(0)}KB`);
